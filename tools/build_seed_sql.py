"""Port the floodsense_seed contract views from Lightning SQL to Postgres.

Source of truth is the monorepo, not this file:
  - the row data in zetaris/migrations/012 and 013 (Urvashi, frozen Open-Meteo
    answers for 20 Oct - 5 Nov 2024)
  - the CSVs under ingestion/prep (Saleeta)
  - the view definitions in 012, 013, 016 and 017

Nothing here invents a number. Re-run it when those migrations change.
"""

from __future__ import annotations

import csv
import pathlib
import re
import sys

REPO = pathlib.Path("H:/Hackathon-Monorepo")
OUT = pathlib.Path(sys.argv[1]) if len(sys.argv) > 1 else pathlib.Path("seed.sql")

# --- reading Lightning's FROM VALUES blocks -------------------------------

TUPLE = re.compile(r"^\s*\((.*)\)\s*,?\s*$")


def cells(line: str) -> list[str] | None:
    """One `('a', 'b', 1.0D, NULL)` row, as Postgres literals."""
    m = TUPLE.match(line)
    if not m:
        return None
    out, buf, quoted = [], "", False
    for ch in m.group(1):
        if ch == "'":
            quoted = not quoted
            buf += ch
        elif ch == "," and not quoted:
            out.append(buf.strip())
            buf = ""
        else:
            buf += ch
    out.append(buf.strip())
    # Lightning writes doubles as 1.0D; Postgres does not.
    return [re.sub(r"^(-?[\d.]+)D$", r"\1", c) for c in out]


def values_of(path: pathlib.Path) -> list[list[str]]:
    rows: list[list[str]] = []
    seen_values = False
    for line in path.read_text(encoding="utf-8").splitlines():
        if not seen_values:
            seen_values = line.strip().upper().startswith("FROM VALUES")
            continue
        got = cells(line)
        if got:
            rows.append(got)
    return rows


def stated_min_rows(path: pathlib.Path) -> int | None:
    m = re.search(r"--\s*min_rows:\s*(\d+)", path.read_text(encoding="utf-8"))
    return int(m.group(1)) if m else None


# --- reading Saleeta's CSVs -----------------------------------------------


def csv_rows(name: str) -> tuple[list[str], list[list[str]]]:
    with (REPO / "ingestion/prep" / f"{name}.csv").open(encoding="utf-8-sig", newline="") as fh:
        r = csv.reader(fh)
        head = next(r)
        return head, [row for row in r if any(c.strip() for c in row)]


def lit(v: str) -> str:
    if v == "" or v.upper() == "NULL":
        return "NULL"
    return "'" + v.replace("'", "''") + "'"


def inserts(table: str, cols: list[str], rows: list[list[str]], raw: bool) -> list[str]:
    out = []
    for i in range(0, len(rows), 200):  # one statement per 200 rows keeps it readable
        chunk = rows[i : i + 200]
        vals = ",\n  ".join(
            "(" + ", ".join(c if raw else lit(c) for c in row) + ")" for row in chunk
        )
        out.append(f"INSERT INTO {table} ({', '.join(cols)}) VALUES\n  {vals};")
    return out


# --- build ----------------------------------------------------------------

mig = REPO / "zetaris/migrations"
hazard = values_of(mig / "013_create_seed_view_hazard_timeline.sql")
discharge = values_of(mig / "012_create_seed_view_discharge_daily.sql")

sites_cols, sites = csv_rows("osm_sites")
pf_cols, pf = csv_rows("portfolio_synthetic")
prov_cols, prov = csv_rows("provenance")

parts: list[str] = [
    "-- Generated by tools/build_seed_sql.py from the FloodSense monorepo.",
    "-- Row data: zetaris/migrations/012 and 013. CSVs: ingestion/prep.",
    "-- View definitions: migrations 012, 013, 016, 017. Do not edit by hand.",
    "",
    "CREATE SCHEMA IF NOT EXISTS floodsense_seed_src;",
    "CREATE SCHEMA IF NOT EXISTS floodsense_seed;",
    "",
    "DROP TABLE IF EXISTS floodsense_seed_src.hazard_timeline_rows CASCADE;",
    "CREATE TABLE floodsense_seed_src.hazard_timeline_rows ("
    "point_id text, ts_utc text, rain_mm double precision, discharge_m3s double precision);",
]
parts += inserts(
    "floodsense_seed_src.hazard_timeline_rows",
    ["point_id", "ts_utc", "rain_mm", "discharge_m3s"],
    hazard,
    raw=True,
)

parts += [
    "",
    "DROP TABLE IF EXISTS floodsense_seed_src.discharge_daily_rows CASCADE;",
    "CREATE TABLE floodsense_seed_src.discharge_daily_rows ("
    "point_id text, date text, discharge_m3s double precision, source text);",
]
parts += inserts(
    "floodsense_seed_src.discharge_daily_rows",
    ["point_id", "date", "discharge_m3s", "source"],
    discharge,
    raw=True,
)

parts += [
    "",
    "DROP TABLE IF EXISTS floodsense_seed_src.osm_sites CASCADE;",
    "CREATE TABLE floodsense_seed_src.osm_sites ("
    + ", ".join(
        f"{c} double precision" if c in ("lat", "lon") else f"{c} text" for c in sites_cols
    )
    + ");",
]
parts += inserts("floodsense_seed_src.osm_sites", sites_cols, sites, raw=False)

parts += [
    "",
    "DROP TABLE IF EXISTS floodsense_seed_src.portfolio_synthetic CASCADE;",
    "CREATE TABLE floodsense_seed_src.portfolio_synthetic ("
    + ", ".join(
        f"{c} double precision" if c in ("sum_insured_eur", "deductible_eur") else f"{c} text"
        for c in pf_cols
    )
    + ");",
]
parts += inserts("floodsense_seed_src.portfolio_synthetic", pf_cols, pf, raw=False)

parts += [
    "",
    "DROP TABLE IF EXISTS floodsense_seed_src.provenance CASCADE;",
    "CREATE TABLE floodsense_seed_src.provenance ("
    + ", ".join(f"{c} text" for c in prov_cols)
    + ");",
]
parts += inserts("floodsense_seed_src.provenance", prov_cols, prov, raw=False)

# The four contract views, same SELECTs as the Lightning migrations.
parts += [
    "",
    "-- migration 013",
    "CREATE OR REPLACE VIEW floodsense_seed.hazard_timeline AS",
    "SELECT point_id,",
    "       CAST(ts_utc AS timestamp) AS ts_utc,",
    "       CAST(rain_mm AS double precision) AS rain_mm,",
    "       CAST(discharge_m3s AS double precision) AS discharge_m3s,",
    "       CAST(NULL AS text) AS warning_level",
    "FROM floodsense_seed_src.hazard_timeline_rows;",
    "",
    "-- migration 012",
    "CREATE OR REPLACE VIEW floodsense_seed.discharge_daily AS",
    "SELECT point_id,",
    "       CAST(date AS date) AS date,",
    "       CAST(discharge_m3s AS double precision) AS discharge_m3s,",
    "       source",
    "FROM floodsense_seed_src.discharge_daily_rows;",
    "",
    "-- migration 016",
    "CREATE OR REPLACE VIEW floodsense_seed.exposure_join AS",
    "SELECT p.policy_id,",
    "       p.site_id,",
    "       s.lat,",
    "       s.lon,",
    "       (s.in_flood_footprint = 'yes') AS in_footprint,",
    "       CAST(p.sum_insured_eur AS double precision) AS sum_insured_eur,",
    "       s.site_type AS segment",
    "FROM floodsense_seed_src.portfolio_synthetic p",
    "JOIN floodsense_seed_src.osm_sites s ON s.site_id = p.site_id;",
    "",
    "-- migration 017",
    "CREATE OR REPLACE VIEW floodsense_seed.provenance AS",
    "SELECT dataset, source_url, publisher, licence, attribution,",
    "       CAST(accessed_at AS timestamp) AS fetched_at",
    "FROM floodsense_seed_src.provenance;",
    "",
]

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(parts) + "\n", encoding="utf-8")

# --- report against what the migrations say they hold ---------------------
print(f"wrote {OUT} ({OUT.stat().st_size // 1024} KB)")
for name, rows, src in (
    ("hazard_timeline", hazard, mig / "013_create_seed_view_hazard_timeline.sql"),
    ("discharge_daily", discharge, mig / "012_create_seed_view_discharge_daily.sql"),
):
    want = stated_min_rows(src)
    ok = "ok" if want is None or len(rows) >= want else "SHORT"
    print(f"  {name:<18} {len(rows):>5} rows (migration says min_rows {want}) {ok}")
print(f"  osm_sites          {len(sites):>5} rows")
print(f"  portfolio          {len(pf):>5} rows")
print(f"  provenance         {len(prov):>5} rows")
print(f"  exposure_join      joins portfolio to sites (migration 016 says min_rows 359)")
